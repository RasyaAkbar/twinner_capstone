/**
 * Resolve local references generated by Pydantic.
 * Example: #/$defs/DateRange
 */
export function resolveSchema(
  schema: ParameterSchema,
  root: ParameterSchema,
): ParameterSchema {
  if (schema.$ref) {
    const segments = schema.$ref
      .replace(/^#\//, '')
      .split('/')
      .map((segment) =>
        segment.replaceAll('~1', '/').replaceAll('~0', '~'),
      );

    let target: unknown = root;

    for (const segment of segments) {
      if (!target || typeof target !== 'object') {
        return schema;
      }

      target = (target as Record<string, unknown>)[segment];
    }

    if (target && typeof target === 'object') {
      const { $ref: _ref, ...overrides } = schema;

      return resolveSchema(
        {
          ...(target as ParameterSchema),
          ...overrides,
        },
        root,
      );
    }
  }

  if (schema.anyOf) {
    const nonNull = schema.anyOf.find(
      (item) => item.type !== 'null',
    );

    if (nonNull) {
      const { anyOf: _anyOf, ...overrides } = schema;

      return {
        ...resolveSchema(nonNull, root),
        ...overrides,
      };
    }
  }

  if (schema.allOf) {
    const { allOf, ...overrides } = schema;

    return {
      ...Object.assign(
        {},
        ...allOf.map((item) => resolveSchema(item, root)),
      ),
      ...overrides,
    };
  }

  return schema;
}

/**
 * Generate empty form values without inventing
 * project IDs, resource IDs, or dates.
 */
export function createInitialValue(
  schema: ParameterSchema,
  root: ParameterSchema,
): unknown {
  const resolved = resolveSchema(schema, root);

  if (resolved.default !== undefined) {
    return structuredClone(resolved.default);
  }

  switch (resolved.type) {
    case 'object':
      return Object.fromEntries(
        Object.entries(resolved.properties ?? {}).map(
          ([key, field]) => [
            key,
            createInitialValue(field, root),
          ],
        ),
      );

    case 'array':
      return [];

    case 'boolean':
      return false;

    case 'integer':
    case 'number':
      return '';

    case 'string':
      return '';

    default:
      return null;
  }
}

export function createInitialParameters(
  schema: ParameterSchema,
): Parameters {
  const resolved = resolveSchema(schema, schema);

  return Object.fromEntries(
    Object.entries(resolved.properties ?? {}).map(
      ([key, field]) => [
        key,
        createInitialValue(field, schema),
      ],
    ),
  );
}

/**
 * Prepare form values before sending them to the API.
 * Empty fields are omitted so the backend can apply
 * defaults or return required-field validation errors.
 */
export function serializeParameters(
  parameters: Parameters,
): Parameters {
  function clean(value: unknown): unknown {
    if (value === '') return undefined;

    if (Array.isArray(value)) {
      return value
        .map(clean)
        .filter((item) => item !== undefined);
    }

    if (value !== null && typeof value === 'object') {
      return Object.fromEntries(
        Object.entries(value)
          .map(([key, item]) => [key, clean(item)])
          .filter(([, item]) => item !== undefined),
      );
    }

    return value;
  }

  return clean(parameters) as Parameters;
}
